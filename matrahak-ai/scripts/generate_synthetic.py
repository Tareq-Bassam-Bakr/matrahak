def generate(per_category: int = PER_CATEGORY, seed: int = SEED) -> list[tuple[str, str, str]]:
    """يعيد (النص، التصنيف، المجموعة). المجموعة = قالب الجملة: يُستخدم في Grouped Cross-Validation
    حتى لا تظهر نفس الجملة في التدريب والتحقق معاً (وإلا تكون الدقة مضخّمة)."""
    rng = random.Random(seed)
    rows: list[tuple[str, str, str]] = []
    for slug, spec in CATEGORIES.items():
        seen: set[str] = set()
        attempts = 0
        while len(seen) < per_category and attempts < per_category * 40:
            attempts += 1
            bi = rng.randrange(len(spec["bodies"]))
            title = rng.choice(spec["titles"])
            body = spec["bodies"][bi].format(place=rng.choice(PLACES), duration=rng.choice(DURATIONS))
            body = " ".join(body.split())
            text = f"{title} — {rng.choice(OPENERS)}{body}.{rng.choice(CLOSINGS)}".replace("..", ".")
            if text not in seen:
                seen.add(text)
                rows.append((text, slug, f"{slug}:{bi}"))
    rng.shuffle(rows)
    return rows


def main() -> None:
    out = Path(__file__).resolve().parent.parent / "data" / "synthetic_train.csv"
    rows = generate()
    with out.open("w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["text", "label", "source", "group"])
        for text, label, group in rows:
            w.writerow([text, label, "synthetic", group])
    print(f"wrote {len(rows)} rows ({len(CATEGORIES)} categories) -> {out}")


if __name__ == "__main__":
    main()
